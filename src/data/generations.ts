export function generationsFor(make: string, model: string): Generation[] {
  return GENERATIONS[make]?.[model] ?? [];
}

/** "Golf IV (Mk4) (1997–2003)", as shown in the generation dropdown. */
export const generationLabel = (g: Generation) => `${g.name} (${g.from}–${g.to ?? 'today'})`;

/** "1.9 TDI:90/110" with "diesel" → "1.9 TDI diesel · 90 hp", "1.9 TDI diesel · 110 hp". */
function engineNames(list: string[] | undefined, fuel: string): string[] {
  return (list ?? []).flatMap((entry) => {
    const [engine, powers] = entry.split(':');
    const name = fuel ? `${engine} ${fuel}` : engine;
    return powers ? powers.split('/').map((hp) => `${name} · ${hp} hp`) : [name];
  });
}

/** The engines of a generation, grouped by fuel for the engine dropdown. */
export function enginesFor(g: Generation | undefined): OptionGroup[] {
  if (!g) return [];
  return [
    { label: 'Petrol (essence)', options: engineNames(g.petrol, 'petrol') },
    { label: 'Diesel', options: engineNames(g.diesel, 'diesel') },
    { label: 'Hybrid, electric, LPG', options: engineNames(g.other, '') },
  ].filter((group) => group.options.length > 0);
}
